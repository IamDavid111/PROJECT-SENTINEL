// Generates src/lib/hugeicons-partial.ts — a filtered HugeIcons collection
// containing only the icons referenced by src/lib/icons.ts.
//
// Run after adding/removing icons in the registry:
//   node scripts/generate-hugeicons.mjs
//
// This exists so the bundle never ships the full 6,091-icon JSON while the
// Icon component stays fully offline. The output file is checked in because the
// app imports it at runtime (unlike the git-ignored rophi/ workbench).
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const iconsPath = resolve(root, 'src/lib/icons.ts')
const outPath = resolve(root, 'src/lib/hugeicons-partial.ts')

const set = require('@iconify-json/hugeicons').icons // { prefix, icons, aliases, width, height }

const source = readFileSync(iconsPath, 'utf8')
const usedNames = [...source.matchAll(/['"]hugeicons:([a-z0-9-]+)['"]/g)].map((match) => match[1])
if (usedNames.length === 0) {
  console.error('No hugeicons: references found in src/lib/icons.ts')
  process.exit(1)
}

// Resolve a name to icon data (primary icon or alias chain).
function resolveIcon(name, seen = new Set()) {
  if (set.icons[name]) return set.icons[name]
  const alias = set.aliases?.[name]
  if (alias && !seen.has(name)) {
    seen.add(name)
    const parent = resolveIcon(alias.parent, seen)
    if (!parent) return null
    return { ...parent, ...(alias.rotate ? { rotate: alias.rotate } : {}), ...(alias.hFlip ? { hFlip: 1 } : {}), ...(alias.vFlip ? { vFlip: 1 } : {}) }
  }
  return null
}

const unique = [...new Set(usedNames)]
const icons = {}
const missing = []
for (const name of unique) {
  const data = resolveIcon(name)
  if (!data) missing.push(name)
  else icons[name] = data
}

if (missing.length) {
  console.error('Missing HugeIcons: ' + missing.join(', '))
  process.exit(1)
}

const output = `// AUTO-GENERATED by scripts/generate-hugeicons.mjs — do not edit by hand.
// Filtered HugeIcons collection containing only the icons used by src/lib/icons.ts,
// keeping the bundle small while the Icon component stays fully offline.
export const hugeiconsPartial = ${JSON.stringify({ prefix: set.prefix, width: set.width, height: set.height, icons })}
`
writeFileSync(outPath, output)
console.log(`Generated ${outPath} (${Object.keys(icons).length} of ${usedNames.length} icons referenced)`)